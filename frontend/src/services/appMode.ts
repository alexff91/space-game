/**
 * Режим работы приложения.
 *
 * ПОЧЕМУ отдельный модуль: раньше эта проверка жила рядом с выдуманными
 * данными и называлась «демо-режим» — то есть подразумевала, что при
 * отсутствии бэкенда данные надо чем-то подменить. Подменять нечем.
 * Единственный честный ответ на «бэкенда нет» — сказать об этом.
 */

/** Настроен ли настоящий бэкенд, у которого есть что спрашивать. */
export function isBackendConfigured(): boolean {
  const apiUrl = import.meta.env.VITE_API_URL;
  if (import.meta.env.VITE_DEMO_MODE === 'true') return false;
  // '/api' — значение по умолчанию в статической сборке, за ним никого нет.
  return !!apiUrl && apiUrl !== '/api';
}

/** Сборка без бэкенда: очков, рейтинга и сохранения разметки не существует. */
export function isDemoMode(): boolean {
  return !isBackendConfigured();
}
